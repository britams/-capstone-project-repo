def name_of(label):
    for key, ko, kind, spec in PART_IN:
        if key in label:
            g = GATE.get(label[:3], "")
            return key, (g + " " + ko).strip(), kind, spec
    for head, ko, kind, spec in NAMES:
        if label.startswith(head):
            return head, ko, kind, spec
    return None, label.split(" ")[0], "?", ""


def table(doc):
    rows, miss = [], []
    for o in doc.Objects:
        if not hasattr(o, "Shape") or o.TypeId == "App::DocumentObjectGroup" or o.Shape.isNull():
            continue
        if App.GuiUp and not o.ViewObject.Visibility:
            continue
        if "beam" in o.Label and o.Label.startswith("196_"):
            continue
        head, ko, kind, spec = name_of(o.Label)
        if head is None:
            miss.append(o.Label)
        n = len(o.Shape.Solids) if o.Shape.Solids else 1
        rows.append((o.Label.split("_")[0], ko, kind, spec, n, o.Label.split(" ")[0]))
    rows.sort(key=lambda r: (r[0].replace("REF", "999"), r[5]))
    return rows, miss


